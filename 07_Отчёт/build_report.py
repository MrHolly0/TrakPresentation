def write_markdown(blocks: list[dict]) -> None:
    lines: list[str] = []
    for b in blocks:
        if b["type"] == "heading":
            level = b["level"]
            if level == 0:
                lines.append(f"# {b['text']}")
            else:
                lines.append("#" * level + " " + b["text"])
        elif b["type"] == "p":
            lines.append(b["text"])
        elif b["type"] == "table":
            lines.append(b["title"])
            lines.append(md_table(b["rows"]))
        elif b["type"] == "image":
            img_path = str(b["path"])
            lines.append(f"{b['title']}\n\n![{b['title']}]({img_path})")
            if b.get("note"):
                lines.append(b["note"])
        lines.append("")
    REPORT_MD.write_text("\n".join(lines), encoding="utf-8")


def set_cell_text(cell, text: str, font_size: int = 10, bold: bool = False) -> None:
    cell.text = ""
    p = cell.paragraphs[0]
    run = p.add_run(str(text))
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(font_size)
    run.bold = bold
    p.paragraph_format.line_spacing = 1.0
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if len(str(text)) < 16 else WD_ALIGN_PARAGRAPH.LEFT
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER


def add_page_number(section) -> None:
    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run = footer.add_run()
    fld_char1 = OxmlElement("w:fldChar")
    fld_char1.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = "PAGE"
    fld_char2 = OxmlElement("w:fldChar")
    fld_char2.set(qn("w:fldCharType"), "end")
    run._r.append(fld_char1)
    run._r.append(instr)
    run._r.append(fld_char2)


def add_toc(paragraph) -> None:
    run = paragraph.add_run()
    fld_char1 = OxmlElement("w:fldChar")
    fld_char1.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = r'TOC \o "1-3" \h \z \u'
    fld_char2 = OxmlElement("w:fldChar")
    fld_char2.set(qn("w:fldCharType"), "separate")
    text = OxmlElement("w:t")
    text.text = "Оглавление обновить в Word: Ссылки → Оглавление → Обновить таблицу."
    fld_char3 = OxmlElement("w:fldChar")
    fld_char3.set(qn("w:fldCharType"), "end")
    run._r.append(fld_char1)
    run._r.append(instr)
    run._r.append(fld_char2)
    run._r.append(text)
    run._r.append(fld_char3)


def setup_doc() -> Document:
    doc = Document()
    section = doc.sections[0]
    section.top_margin = Mm(20)
    section.bottom_margin = Mm(20)
    section.left_margin = Mm(30)
    section.right_margin = Mm(15)
    section.different_first_page_header_footer = True
    add_page_number(section)

    styles = doc.styles
    normal = styles["Normal"]
    normal.font.name = "Times New Roman"
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    normal.font.size = Pt(14)
    normal.paragraph_format.line_spacing = 1.5
    normal.paragraph_format.first_line_indent = Cm(1.25)
    normal.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    normal.paragraph_format.space_after = Pt(0)

    for style_name in ["Heading 1", "Heading 2", "Heading 3"]:
        style = styles[style_name]
        style.font.name = "Times New Roman"
        style._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        style.font.size = Pt(14)
        style.font.bold = True
        style.paragraph_format.line_spacing = 1.5
        style.paragraph_format.space_before = Pt(0)
        style.paragraph_format.space_after = Pt(6)

    styles["Heading 1"].paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    styles["Heading 1"].paragraph_format.first_line_indent = Cm(0)
    styles["Heading 2"].paragraph_format.first_line_indent = Cm(1.25)
    return doc


def add_paragraph(doc: Document, text: str, align=None, bold=False) -> None:
    for part in str(text).split("\n"):
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(1.25)
        p.paragraph_format.line_spacing = 1.5
        p.alignment = align if align is not None else WD_ALIGN_PARAGRAPH.JUSTIFY
        run = p.add_run(part)
        run.font.name = "Times New Roman"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        run.font.size = Pt(14)
        run.bold = bold


def write_docx(blocks: list[dict]) -> None:
    doc = setup_doc()
    first_h1 = True
    for b in blocks:
        if b["type"] == "heading":
            level = b["level"]
            text = b["text"]
            if level == 0:
                p = doc.add_paragraph()
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                p.paragraph_format.first_line_indent = Cm(0)
                r = p.add_run("Титульный лист")
                r.font.name = "Times New Roman"
                r._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
                r.font.size = Pt(14)
                r.bold = True
            elif level == 1:
                if not first_h1:
                    doc.add_page_break()
                first_h1 = False
                p = doc.add_heading(text.upper() if text.startswith("Глава") else text, level=1)
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                if text == "Содержание":
                    add_toc(doc.add_paragraph())
            else:
                doc.add_heading(text, level=min(level, 3))
        elif b["type"] == "p":
            add_paragraph(doc, b["text"])
        elif b["type"] == "table":
            cap = doc.add_paragraph()
            cap.paragraph_format.first_line_indent = Cm(0)
            cap.alignment = WD_ALIGN_PARAGRAPH.LEFT
            run = cap.add_run(b["title"])
            run.font.name = "Times New Roman"
            run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
            run.font.size = Pt(12)
            rows = [[clean_cell(c) for c in row] for row in b["rows"] if any(clean_cell(c) for c in row)]
            if rows:
                width = max(len(r) for r in rows)
                rows = [r + [""] * (width - len(r)) for r in rows]
                tbl = doc.add_table(rows=len(rows), cols=width)
                tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
                tbl.style = "Table Grid"
                for i, row in enumerate(rows):
                    for j, val in enumerate(row):
                        set_cell_text(tbl.cell(i, j), val, font_size=9 if width >= 5 else 10, bold=(i == 0))
        elif b["type"] == "image":
            raw_path = Path(b["path"])
            path = raw_path if raw_path.is_absolute() else ROOT / raw_path
            if path.suffix.lower() == ".png" and path.exists():
                try:
                    doc.add_picture(str(path), width=Cm(9) if path == MASTER_IMAGE else Cm(15))
                except Exception:
                    add_paragraph(doc, f"[Не удалось вставить изображение: {b['path']}]")
            else:
                add_paragraph(doc, f"[Исходный файл приложения: {b['path']}]")
            cap = doc.add_paragraph()
            cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
            cap.paragraph_format.first_line_indent = Cm(0)
            run = cap.add_run(b["title"])
            run.font.name = "Times New Roman"
            run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
            run.font.size = Pt(12)
            if b.get("note"):
                add_paragraph(doc, b["note"])
    doc.save(REPORT_DOCX)


